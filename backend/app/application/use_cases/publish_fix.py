from dataclasses import dataclass

from app.application.ports.github_port import FileUpdate, GitHubError, GitHubPort
from app.domain.entities.fix_proposal import FixProposal
from app.domain.entities.pull_request import PullRequest
from app.domain.services.branches import fix_branch_name

MAX_BODY_CHARS = 6000


class FixPublishError(Exception):
    """The proposal cannot be published (stale, fork PR, nothing to publish...)."""


@dataclass(frozen=True)
class PublishedFix:
    branch: str
    commit_sha: str
    pull_request_url: str


def defuse_mentions(text: str) -> str:
    """Model-written text must not be able to ping people or teams."""
    return text.replace("@", "@\u200b")


def build_pr_body(pr: PullRequest, proposal: FixProposal) -> str:
    notes = "\n".join(f"- {note}" for note in proposal.notes) or "- none"
    body = (
        f"Automated fixes proposed for #{pr.number} by PR-Review-Assistant.\n\n"
        f"Merge this pull request into `{pr.head_branch}` to apply the fixes, "
        "or close it to discard them.\n\n"
        f"### Changes\n{proposal.summary}\n\n"
        f"### Validation\n- status: {proposal.status}\n- attempts: {proposal.attempts}\n{notes}\n"
    )
    return defuse_mentions(body)[:MAX_BODY_CHARS]


class PublishFix:
    """Pushes a proposal to a NEW branch and opens a PR into the PR's own branch.

    Never writes to the PR branch or to main, so a human always merges the result.
    """

    def __init__(self, github: GitHubPort) -> None:
        self._github = github

    async def execute(
        self, repo_full_name: str, pr_number: int, proposal: FixProposal
    ) -> PublishedFix:
        if not proposal.publishable:
            raise FixPublishError("the proposal has no changes that can be published")
        pr = await self._github.get_pull_request(repo_full_name, pr_number)
        if pr.from_fork:
            raise FixPublishError("publishing fixes for pull requests from forks is not supported")
        if pr.head_sha != proposal.base_sha:
            raise FixPublishError("the pull request changed since the fixes were generated")

        branch = fix_branch_name(pr.number, pr.head_sha)
        try:
            commit_sha = await self._github.commit_files_to_new_branch(
                pr.repo_full_name,
                pr.head_sha,
                branch,
                (
                    f"fix: address review findings for #{pr.number}\n\n"
                    "Generated by PR-Review-Assistant."
                ),
                [FileUpdate(c.path, c.new_content) for c in proposal.changes],
            )
        except GitHubError as exc:
            if exc.status_code == 422:
                raise FixPublishError("a fix branch for this commit already exists") from exc
            raise
        url = await self._github.open_pull_request(
            pr.repo_full_name,
            head=branch,
            base=pr.head_branch,
            title=f"Automated fixes for #{pr.number}",
            body=build_pr_body(pr, proposal),
        )
        return PublishedFix(branch, commit_sha, url)
